export const getCFSCodesForLocation = (locId, locNm = "") => {
  if (!locId && !locNm) return CFS_LOCATION_MASTER;

  const results = [];
  const seen = new Set();

  const addEntries = (list) => {
    if (!Array.isArray(list)) return;
    for (const item of list) {
      if (item && item.value && !seen.has(item.value)) {
        seen.add(item.value);
        results.push(item);
      }
    }
  };

  if (locId) {
    const normLoc = locId.toUpperCase().trim();
    const prefix5 = normLoc.substring(0, 5).toLowerCase();
    if (CFS_BY_LOCATION_MAP[prefix5]) {
      addEntries(CFS_BY_LOCATION_MAP[prefix5]);
    } else {
      const matched = CFS_LOCATION_MASTER.filter(c => c.value.toUpperCase().startsWith(prefix5) || c.value.toUpperCase().startsWith(normLoc));
      addEntries(matched);
    }
  }

  if (results.length === 0 && locNm) {
    const normNm = locNm.toLowerCase().trim();
    const matched = CFS_LOCATION_MASTER.filter(c => c.locNm && c.locNm.toLowerCase().includes(normNm));
    addEntries(matched);
  }

  if (results.length === 0) return CFS_LOCATION_MASTER;
  return results.sort((a, b) => (a.label || "").localeCompare(b.label || ""));
};

export default CFS_LOCATION_MASTER;
